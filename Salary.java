package Assigment3;
import java.util.*;

public class Salary {

	public static void main(String[] args) {
		Scanner scan = new Scanner(System.in);
		
		int salary = scan.nextInt();
		

		salary += 200;
		System.out.println(salary);
		
		salary -= 300;
		System.out.println(salary);
		
		salary *= 2;
		System.out.println(salary);
		
		salary /= 3;
		System.out.println(salary);

	}

}
